#!/usr/bin/env bash
# FoodX — vendor backup for ONE client deployment (Phase 8 R3, §59).
#
# Runs pg_dump against the client's own database, stores the dump
# under a dated path on the vendor machine, and reports the outcome
# to the FoodX registry (report-backup Edge Function), so the
# Developer Panel's backup health reflects reality. A failed dump
# is reported as 'failed' too — silence would read as "no news",
# which is exactly what a backup system must never produce.
#
# The client's database password lives in the vendor's vault, never
# in this repo: pass the full connection string via DATABASE_URL.
# For Supabase projects use the pooler string from the dashboard
# (Connect → Session pooler), e.g.
#   postgresql://postgres.<ref>:<password>@aws-0-<region>.pooler.supabase.com:6543/postgres
#
# Required environment:
#   DATABASE_URL        client database connection string (vault)
#   REGISTRY_URL        e.g. https://<registry-ref>.supabase.co
#   REGISTRY_ANON_KEY   the registry project's public anon key
#   INSTANCE_ID         the client's code in the registry (CL-001)
#   INSTANCE_TOKEN      the client's instance token (fx_…, vault)
# Optional:
#   BACKUP_DIR          root for dumps (default: ./backups)
#   BACKUP_KIND         label stored in the report note (default: scheduled)
#
# Requires: pg_dump (postgresql-client) and curl on the vendor machine.
# Scheduling is an ops choice (vendor cron / Task Scheduler / GitHub
# Actions with the secrets above) — see the deployment runbook.
#
# Exit code: 0 when the dump succeeded (regardless of whether the
# report call itself succeeded — a registry outage must not fail a
# good backup; the next run reports again), 1 when the dump failed.

set -uo pipefail

: "${DATABASE_URL:?DATABASE_URL is required (client connection string from the vault)}"
: "${REGISTRY_URL:?REGISTRY_URL is required}"
: "${REGISTRY_ANON_KEY:?REGISTRY_ANON_KEY is required}"
: "${INSTANCE_ID:?INSTANCE_ID is required (e.g. CL-001)}"
: "${INSTANCE_TOKEN:?INSTANCE_TOKEN is required}"

BACKUP_DIR="${BACKUP_DIR:-./backups}"
BACKUP_KIND="${BACKUP_KIND:-scheduled}"
STAMP="$(date +%Y%m%d-%H%M%S)"
CLIENT_DIR="${BACKUP_DIR}/${INSTANCE_ID}"
TMP_FILE="$(mktemp)"
trap 'rm -f "${TMP_FILE}"' EXIT

report() {
  # $1 = status (success|failed), $2 = size_bytes or empty, $3 = note
  local status="$1" size="$2" note="$3"
  local size_json="null"
  [ -n "${size}" ] && size_json="${size}"
  # The note is generated by this script (kind + pg_dump's first
  # error line, sanitised below), so plain interpolation is safe.
  local payload
  payload=$(printf '{"instance_id":"%s","token":"%s","status":"%s","size_bytes":%s,"note":"%s"}' \
    "${INSTANCE_ID}" "${INSTANCE_TOKEN}" "${status}" "${size_json}" "${note}")
  curl -s -X POST "${REGISTRY_URL}/functions/v1/report-backup" \
    -H "apikey: ${REGISTRY_ANON_KEY}" \
    -H "Authorization: Bearer ${REGISTRY_ANON_KEY}" \
    -H 'Content-Type: application/json' \
    --data "${payload}" > /dev/null || true
}

mkdir -p "${CLIENT_DIR}"

echo "Backing up ${INSTANCE_ID}…"
if pg_dump "${DATABASE_URL}" --no-owner --no-privileges -f "${TMP_FILE}" 2>"${TMP_FILE}.err"; then
  SIZE=$(stat -c %s "${TMP_FILE}" 2>/dev/null || stat -f %z "${TMP_FILE}")
  DEST="${CLIENT_DIR}/${STAMP}.sql"
  mv "${TMP_FILE}" "${DEST}"
  echo "Backup written: ${DEST} (${SIZE} bytes)"
  report "success" "${SIZE}" "${BACKUP_KIND} backup"
  exit 0
else
  ERR_LINE=$(head -n 1 "${TMP_FILE}.err" | tr -d '"\\' | cut -c 1-200)
  echo "pg_dump FAILED for ${INSTANCE_ID}: ${ERR_LINE}" >&2
  report "failed" "" "${BACKUP_KIND} backup failed: ${ERR_LINE}"
  exit 1
fi
