/** True when the signed-in user's profile is on the developer
 * allow-list (dev_developers). RLS enforces the same check on every
 * dev_* table; this is only for routing the UI. */
export async function checkIsDeveloper(userId: string): Promise<boolean> {
  const { data, error } = await supabase
    .from('dev_developers')
    .select('profile_id')
    .eq('profile_id', userId)
  if (error) throw error
  return (data ?? []).length > 0
}

