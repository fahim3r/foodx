/** Enabled state for all six keys; missing rows read as disabled. */
export function featureStateMap(
  rows: DevClientFeature[],
): Record<DevFeatureKey, boolean> {
  const map = {} as Record<DevFeatureKey, boolean>
  for (const key of DEV_FEATURE_KEYS) map[key] = false
  for (const row of rows) map[row.feature_key] = row.is_enabled
  return map
}

