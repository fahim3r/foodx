async function sha256Hex(value: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    'SHA-256',
    new TextEncoder().encode(value),
  )
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('')
}

/**
 * Issue (or rotate) the client's instance token. The plaintext is
 * returned ONCE for the developer to copy into that deployment's env
 * (VITE_FOODX_INSTANCE_TOKEN); only its SHA-256 hash is stored, so
 * rotating immediately invalidates the previous token.
 */
export async function generateInstanceToken(
  clientId: string,
): Promise<string> {
  const bytes = new Uint8Array(24)
  crypto.getRandomValues(bytes)
  const token =
    'fx_' +
    [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('')
  const hash = await sha256Hex(token)
  const { error } = await supabase
    .from('dev_clients')
    .update({ instance_token_hash: hash })
    .eq('id', clientId)
  if (error) throw error
  return token
}

