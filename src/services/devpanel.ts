/** Semver-ish compare: numeric per dot segment, missing segments = 0.
 * Returns <0 when a < b, 0 when equal, >0 when a > b. Non-numeric
 * segments compare as strings so odd registered values never crash. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.')
  const pb = b.split('.')
  const len = Math.max(pa.length, pb.length)
  for (let i = 0; i < len; i++) {
    const na = Number(pa[i] ?? 0)
    const nb = Number(pb[i] ?? 0)
    if (Number.isNaN(na) || Number.isNaN(nb)) {
      const sa = pa[i] ?? ''
      const sb = pb[i] ?? ''
      if (sa !== sb) return sa < sb ? -1 : 1
    } else if (na !== nb) {
      return na - nb
    }
  }
  return 0
}

/** The newest PUBLISHED release (the "current version", §50). */
export function latestPublishedRelease(
  releases: DevRelease[],
): DevRelease | null {
  const published = releases.filter((r) => r.status === 'PUBLISHED')
  if (published.length === 0) return null
  return published.reduce((best, r) =>
    compareVersions(r.version, best.version) > 0 ? r : best,
  )
}

/** Clients whose registered version is older than the latest published
 * release (§50 "update pending"). Clients with no registered version or
 * targeted-out of the release are not counted. */
export function updatePendingClients(
  clients: DevClient[],
  releases: DevRelease[],
): DevClient[] {
  const latest = latestPublishedRelease(releases)
  if (!latest) return []
  return clients.filter((c) => {
    if (!c.version) return false
    if (
      latest.target_client_ids !== null &&
      !latest.target_client_ids.includes(c.id)
    ) {
      return false
    }
    return compareVersions(c.version, latest.version) < 0
  })
}

