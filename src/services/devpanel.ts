/** Next CL-### code from the codes already registered. */
function nextClientCode(existing: DevClient[]): string {
  let max = 0
  for (const c of existing) {
    const m = /^CL-(\d+)$/.exec(c.client_code)
    if (m) max = Math.max(max, parseInt(m[1], 10))
  }
  return `CL-${String(max + 1).padStart(3, '0')}`
}

export async function createDevClient(
  input: DevClientInput,
): Promise<DevClient> {
  const existing = await fetchDevClients()
  const { data, error } = await supabase
    .from('dev_clients')
    .insert({
      id: crypto.randomUUID(),
      client_code: nextClientCode(existing),
      ...input,
      status: 'ACTIVE' as DevClientStatus,
    })
    .select('*')
    .single()
  if (error) throw error
  return data as DevClient
}

