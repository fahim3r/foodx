/** Renewal (§52): the old license is marked RENEWED first (the partial
 * unique index allows only one ACTIVE license per client), then the
 * new license row is created ACTIVE. History is never edited away. */
export async function renewDevLicense(
  oldLicense: DevLicense,
  input: DevLicenseInput,
): Promise<DevLicense> {
  const { error: markError } = await supabase
    .from('dev_licenses')
    .update({ status: 'RENEWED' as LicenseStatus })
    .eq('id', oldLicense.id)
  if (markError) throw markError
  return createDevLicense(input, 'ACTIVE')
}

/** The status to DISPLAY for a license: stored status, except an ACTIVE
 * license whose expiry_date has passed reads EXPIRED. LIFETIME licenses
 * (expiry_date NULL) never expire. Pure — computed from the row. */
export function effectiveLicenseStatus(
  license: DevLicense,
  today: string,
): LicenseStatus {
  if (
    license.status === 'ACTIVE' &&
    license.expiry_date !== null &&
    license.expiry_date < today
  ) {
    return 'EXPIRED'
  }
  return license.status
}

/** Whole days from today until expiry; negative when already past.
 * NULL for LIFETIME / no expiry. */
export function licenseDaysLeft(
  license: DevLicense,
  today: string,
): number | null {
  if (license.expiry_date === null) return null
  const ms =
    new Date(`${license.expiry_date}T00:00:00`).getTime() -
    new Date(`${today}T00:00:00`).getTime()
  return Math.round(ms / 86_400_000)
}

/** A client's current license: its newest row that is not CANCELLED or
 * RENEWED (those are history). Null when the client has none. */
export function currentLicenseFor(
  licenses: DevLicense[],
  clientId: string,
): DevLicense | null {
  const rows = licenses.filter(
    (l) =>
      l.client_id === clientId &&
      l.status !== 'CANCELLED' &&
      l.status !== 'RENEWED',
  )
  return rows.length > 0 ? rows[0] : null
}

